export function translate(lang, key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? (lang !== "fa" ? DICT.en[key] : undefined) ?? DICT.fa[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

// Product field in the current language; English fields end in _en and fall back to Persian.
export function pf(product, field, lang) {
  if (lang === "ko" && product[`${field}_ko`] != null) return product[`${field}_ko`];
  if ((lang === "en" || lang === "ko") && product[`${field}_en`] != null) return product[`${field}_en`];
  return product[field];
}

